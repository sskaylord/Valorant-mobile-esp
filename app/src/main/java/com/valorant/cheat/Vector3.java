package com.valorant.cheat;

public class Vector3 {
    public float X;
    public float Y;
    public float Z;
    
    public Vector3() {
        this.X = 0;
        this.Y = 0;
        this.Z = 0;
    }
    
    public Vector3(float x, float y, float z) {
        this.X = x;
        this.Y = y;
        this.Z = z;
    }
}
